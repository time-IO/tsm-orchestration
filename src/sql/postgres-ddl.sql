(
    "id"          bigserial    NOT NULL PRIMARY KEY,
    "name"        varchar(200) NOT NULL,
    "uuid"        uuid         NOT NULL UNIQUE,
    "description" text         NULL,
    "properties"  jsonb        NULL
);


